// Mock data matching Prisma schemas for Thai company analytics

export type JobStatus = "pending" | "in_progress" | "completed" | "cancelled"

export interface Customer {
  id: number
  name: string
  codeCustomer: string
  contactPerson?: string
  phone?: string
}

export interface Staff {
  id: number
  name: string
  position: string
}

export interface Bill {
  id: number
  customerId: number | null
  yourRef: string
  invoiceNo: number
  codeCustomer: string | null
  credit: Date | null
  deliveryDate: Date
  deliveryOrderNo: string | null
  salesName: string | null
  deliveredBy: string | null
  description: string | null
  vatRate: number
  subtotal: number | null
  grandTotal: number | null
  discount: number | null
  vat: number
  dateReceive: Date | null
  salesNameId: number | null
  deliveredById: number | null
  updatedAt: Date
  createdAt: Date
}

export interface OrderPO {
  id: number
  poNumber: string
  customerId: number | null
  billId: number | null
  status: JobStatus
  total: number
  completedAt: Date | null
  urlPo: string[]
  createdAt: Date
  updatedAt: Date
}

export interface StaffSalary {
  id: number
  staffId: number
  amount: number
  effectiveDate: Date
  detail: string | null
  createdBy: number | null
  createdAt: Date
}

export interface StaffIncome {
  id: number
  amount: number
  nameIncome: string
  detail: string
  staffId: number
  date: Date
  typeId: number | null
}

export interface TypeStaffIncome {
  id: number
  amount: number
  name: string
  types: string
}

export interface Expense {
  id: number
  description: string
  amount: number
  expenseDate: Date
  categoryId: number
  receiptUrl: string | null
  createdAt: Date
  updatedAt: Date
}

export interface ExpenseCategory {
  id: number
  name: string
  description: string
  staffId: number
}

